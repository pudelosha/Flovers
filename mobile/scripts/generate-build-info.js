const fs = require("node:fs");
const path = require("node:path");
const zlib = require("node:zlib");
const { execFileSync } = require("node:child_process");

const mobileRoot = path.resolve(__dirname, "..");

// Windows builds may have no Git executable in PATH. Normal CI clones use Git;
// the local fallback reads the current loose commit, including worktree refs.
function readLooseCommit(root) {
  let directory = path.resolve(root);
  while (!fs.existsSync(path.join(directory, ".git"))) {
    const parent = path.dirname(directory);
    if (parent === directory) throw new Error("No Git checkout found.");
    directory = parent;
  }
  let gitDir = path.join(directory, ".git");
  if (fs.statSync(gitDir).isFile()) {
    const pointer = fs.readFileSync(gitDir, "utf8").trim().match(/^gitdir: (.+)$/);
    if (!pointer) throw new Error("Invalid Git directory pointer.");
    gitDir = path.resolve(directory, pointer[1]);
  }
  const commonFile = path.join(gitDir, "commondir");
  const commonDir = fs.existsSync(commonFile)
    ? path.resolve(gitDir, fs.readFileSync(commonFile, "utf8").trim()) : gitDir;
  let sha = fs.readFileSync(path.join(gitDir, "HEAD"), "utf8").trim();
  for (let depth = 0; sha.startsWith("ref: ") && depth < 8; depth += 1) {
    const ref = sha.slice(5);
    if (!/^refs\/[\w./-]+$/.test(ref) || ref.includes("..")) throw new Error("Invalid Git reference.");
    const file = [gitDir, commonDir].map(base => path.join(base, ref)).find(file => fs.existsSync(file));
    if (file) sha = fs.readFileSync(file, "utf8").trim();
    else {
      const packed = fs.readFileSync(path.join(commonDir, "packed-refs"), "utf8");
      sha = packed.split(/\r?\n/).find(line => line.endsWith(` ${ref}`))?.split(" ")[0] ?? "";
    }
  }
  if (!/^[a-f0-9]{40}(?:[a-f0-9]{24})?$/.test(sha)) throw new Error("Cannot resolve the checked-out commit.");
  const object = zlib.inflateSync(fs.readFileSync(path.join(commonDir, "objects", sha.slice(0, 2), sha.slice(2)))).toString("utf8");
  if (!object.startsWith("commit ")) throw new Error("HEAD is not a commit.");
  const committer = object.split("\n\n", 1)[0].match(/^committer .+ (\d+) ([+-])(\d{2})(\d{2})$/m);
  if (!committer) throw new Error("Cannot read the commit date.");
  const offset = (Number(committer[3]) * 60 + Number(committer[4])) * (committer[2] === "+" ? 1 : -1);
  const date = new Date(Number(committer[1]) * 1000 + offset * 60000).toISOString().slice(0, 10);
  return { sha, date };
}

function readCommit(root, runGit = execFileSync) {
  try {
    const result = runGit("git", ["show", "-s", "--format=%H%n%cI", "HEAD"], {
      cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"],
    }).trim().split(/\r?\n/);
    if (!/^[a-f0-9]{40}(?:[a-f0-9]{24})?$/.test(result[0]) || !/^\d{4}-\d{2}-\d{2}T/.test(result[1] ?? "")) {
      throw new Error("Invalid Git metadata.");
    }
    return { sha: result[0], date: result[1].slice(0, 10) };
  } catch {
    try { return readLooseCommit(root); }
    catch (error) {
      throw new Error("Cannot generate app build information. Build from a Git checkout with Git available (required for packed commits).", { cause: error });
    }
  }
}

function generateBuildInfo(root = mobileRoot) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
  const commit = readCommit(root);
  const info = { version: pkg.version, releaseTag: commit.sha.slice(0, 7), releaseDate: commit.date };
  const content = `// Generated by scripts/generate-build-info.js before building the app.\nexport const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;\n`;
  const target = path.join(root, "src", "buildInfo.ts");
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== content) fs.writeFileSync(target, content);
  return info;
}

if (require.main === module) console.log("App build information:", JSON.stringify(generateBuildInfo()));
module.exports = { generateBuildInfo, readCommit };
